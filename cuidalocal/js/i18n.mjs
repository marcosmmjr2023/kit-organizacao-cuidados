const orderedReplacements = [...ENGLISH_REPLACEMENTS].sort(([left], [right]) => right.length - left.length);

export function isEnglishApp(documentLike = globalThis.document) {
  return String(documentLike?.documentElement?.lang || '').toLowerCase().startsWith('en');
}

export function localizeText(value, english = isEnglishApp()) {
  if (!english || typeof value !== 'string') return value;
  return orderedReplacements.reduce((text, [from, to]) => text.split(from).join(to), value);
}

export function localizeHtml(html, english = isEnglishApp()) {
  return localizeText(html, english);
}

export function appLocale(english = isEnglishApp()) {
  return english ? 'en-US' : 'pt-BR';
}
